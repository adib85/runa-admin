/**
 * ═══════════════════════════════════════════════════════════════════════════════
 * XPERT BEAUTY PROVIDER — Product Sync Implementation (CSV / META FEED)
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 * Xpert Beauty (https://www.xpertbeauty.ro) is a Romanian beauty retailer (hair,
 * skin, make-up, nails, body, men's grooming, cosmetic devices). Unlike Bringo /
 * Quicklly this provider does NOT scrape — the merchant supplies a Meta / Facebook
 * catalog feed as a CSV (one row per product). A fresh CSV is dropped daily, so the
 * daily cron just points this provider at the newest file.
 *
 * It plugs into the same SyncOrchestrator / BaseProvider pipeline as everything else,
 * so AI enrichment, embeddings, and the Neo4j write happen in BaseProvider unchanged.
 * Modeled on BringoProvider (RON, Romanian descriptions, categoryHierarchy) — the key
 * difference is the source: read + parse a CSV instead of crawling a website.
 *
 * ─────────────────────────────────────────────────────────────────────────────────
 * USAGE (from apps/api):
 *   node src/scripts/sync-modular.js xpertbeauty <path/to/feed.csv> --max 20 --dry-run
 *   node src/scripts/sync-modular.js xpertbeauty <path/to/feed.csv> --force
 *   node src/scripts/sync-modular.js xpertbeauty <path/to/feed.csv>          # new-only (daily)
 *
 * ─────────────────────────────────────────────────────────────────────────────────
 * FEED → NORMALIZED-PRODUCT MAPPING (Meta catalog columns)
 *   id                         → product id (store-namespaced: "xpertbeauty-<id>")
 *   title                      → title
 *   description                → body_html (already rich Romanian copy → NO AI generation)
 *   brand                      → vendor
 *   product_type "A > B > C"   → collections chain (top→leaf) + categoryHierarchy
 *   price "126 RON"            → list price;  sale_price → current price (Meta semantics)
 *   availability               → inStock ("in stock" / "out of stock")
 *   inventory                  → variant inventory_quantity
 *   image_link / additional_*  → images[]
 *   gtin                       → sku
 *   gender + top category      → demographic (man / woman / unisex — women-first default)
 *   link                       → handle + source_url metafield
 *   color / google_product_category / custom_label_* → metafields
 *
 * Product node key = "xpertbeauty-<feed id>" (namespaced so it can never collide with
 * another store's product in the globally-MERGEd Neo4j Product index — see the big
 * warning in sync-modular.js).
 * ═══════════════════════════════════════════════════════════════════════════════
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import fetch from "node-fetch";
import { BaseProvider } from "./base.js";
import { storePrefixedId } from "../utils/index.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
// Public Meta/Facebook catalog feed (regenerated by the merchant ~2x/day). Passing an http(s)
// URL as csvPath downloads it here first; a local file path is used as-is.
export const XPERTBEAUTY_FEED_URL = "https://conf.xpertbeauty.ro/tools/product_feeds/facebook_feed_1.csv";
const FEED_CACHE_PATH = path.resolve(__dirname, "../../../../data/xpertbeauty_feed_latest.csv");
const STORE_SLUG = "xpertbeauty";      // id prefix (clean, no dots)
const SHOP_NAME = "xpertbeauty.ro";    // tenant key / Neo4j store id / domain

// Feed top-level category (Romanian) → demographic. The store is women-first; the only
// gendered section is "Barbati" (men). Everything else defaults to woman. The `gender`
// column (sparse: mostly empty, some `female`/`male`/`unisex`) refines this per row.
const MEN_TOP_CATEGORY = "barbati";

/**
 * Minimal RFC-4180 CSV parser. Handles quoted fields containing commas, embedded
 * newlines (the `description` column has them) and escaped `""` quotes. The whole
 * file (~16 MB) fits comfortably in memory, so a single pass is fine.
 * Returns an array of row objects keyed by the header names.
 */
function parseCsv(text) {
  const rows = [];
  let field = "";
  let record = [];
  let inQuotes = false;

  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; }  // escaped quote
        else inQuotes = false;                            // closing quote
      } else {
        field += c;
      }
    } else if (c === '"') {
      inQuotes = true;
    } else if (c === ",") {
      record.push(field); field = "";
    } else if (c === "\n") {
      record.push(field); rows.push(record); record = []; field = "";
    } else if (c === "\r") {
      // ignore — CRLF handled by the \n branch
    } else {
      field += c;
    }
  }
  // flush trailing field/record (file may not end with a newline)
  if (field.length > 0 || record.length > 0) { record.push(field); rows.push(record); }

  if (rows.length === 0) return [];
  const header = rows[0].map((h) => h.trim());
  const out = [];
  for (let r = 1; r < rows.length; r++) {
    const cells = rows[r];
    if (cells.length === 1 && cells[0] === "") continue; // skip blank line
    const obj = {};
    for (let c = 0; c < header.length; c++) obj[header[c]] = cells[c] != null ? cells[c] : "";
    out.push(obj);
  }
  return out;
}

function slugify(s) {
  return (s || "")
    .toString()
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

// "126 RON" → 126 ; "10.2 RON" → 10.2 ; "" → null
function parsePrice(s) {
  if (!s) return null;
  const m = String(s).replace(",", ".").match(/[\d]+(?:\.[\d]+)?/);
  return m ? parseFloat(m[0]) : null;
}

export class XpertBeautyProvider extends BaseProvider {
  constructor(config) {
    super(config);

    this.storeSlug = config.storeSlug || STORE_SLUG;
    this.shopName = config.shopName || SHOP_NAME;
    this.csvPath = config.csvPath;

    // The feed already carries rich Romanian descriptions, so the base pipeline must
    // NOT AI-generate one (needsDescription stays false because body_html is set).
    this.descriptionLanguage = "ro";
    this.skipGrounding = true;          // no Google grounding needed
    this.skipSeo = true;                // TOFF-branded SEO is fashion-only
    this.defaultConcurrency = config.aiConcurrency || 5;

    // Internal state
    this.rows = null;                   // parsed feed rows (lazy)
    this.cursorIndex = 0;
    this.stats = { total: 0, inStock: 0, oos: 0, noPrice: 0, men: 0 };
  }

  get providerType() {
    return "xpertbeauty";
  }

  // ─── Feed → product transforms ──────────────────────────────────────────────

  // Women-first store. Men section = the "Barbati" top category or gender=male.
  deriveDemographics(row) {
    const g = (row.gender || "").trim().toLowerCase();
    const topCat = (row.product_type || "").split(">")[0].trim().toLowerCase();
    if (topCat === MEN_TOP_CATEGORY || g === "male") return ["man"];
    if (g === "unisex") return ["unisex"];
    return ["woman"];
  }

  // "Par > Produse Styling > Fixativ" → [{title:"Par"...}, ... , {title:"Fixativ"...}]
  // top→leaf, deduped. determineCategory() picks the leaf as the primary category.
  buildCollections(row) {
    const path = (row.product_type || "").split(">").map((s) => s.trim()).filter(Boolean);
    const collections = [];
    const seen = new Set();
    for (const t of path) {
      const key = t.toLowerCase();
      if (seen.has(key)) continue;
      seen.add(key);
      const handle = slugify(t);
      collections.push({ id: handle || t, title: t, handle: handle || null });
    }
    return collections;
  }

  productHandle(row) {
    if (row.link) {
      try {
        const seg = new URL(row.link).pathname.split("/").filter(Boolean).pop();
        if (seg) return seg;
      } catch { /* fall through */ }
    }
    return slugify(row.title);
  }

  normalizeRow(row) {
    const rawId = (row.id || "").trim();
    const id = storePrefixedId(this.storeSlug, rawId);
    const collections = this.buildCollections(row);
    const leafName = collections.length ? collections[collections.length - 1].title : "";
    const topGroupName = collections.length ? collections[0].title : "";

    // Meta feed semantics: `price` is the list price, `sale_price` is the current
    // selling price when on sale. Current price = sale_price (if lower); compare_at =
    // the struck-through list price when a genuine discount exists.
    const listPrice = parsePrice(row.price);
    const salePrice = parsePrice(row.sale_price);
    let price = listPrice;
    let compareAt = null;
    if (salePrice != null && salePrice > 0) {
      if (listPrice != null && salePrice < listPrice) { price = salePrice; compareAt = listPrice; }
      else if (listPrice == null) { price = salePrice; }
    }

    const inStock = (row.availability || "").trim().toLowerCase() === "in stock";
    const invQty = parseInt(row.inventory, 10);

    const images = [];
    if (row.image_link) images.push({ src: row.image_link, alt: row.title });
    if (row.additional_image_link) images.push({ src: row.additional_image_link, alt: row.title });

    const demographics = this.deriveDemographics(row);

    // stats
    this.stats.total++;
    if (inStock) this.stats.inStock++; else this.stats.oos++;
    if (price == null) this.stats.noPrice++;
    if (demographics[0] === "man") this.stats.men++;

    const body = (row.description || "").trim();

    return {
      id,
      title: (row.title || "").trim(),
      body_html: body,
      descriptionHtml: body,
      handle: this.productHandle(row),
      vendor: (row.brand || "").trim(),
      product_type: leafName,
      status: "active",
      tags: "",
      tagsAsCategories: false,
      published_at: row.launch_date || null,
      price: price ?? null,
      // Sale state on the product itself. The shared sync refreshes these three on EVERY run (stampSeen) and clears
      // them when the product leaves the sale, so the product page can show the shop's regular price crossed out
      // next to the current one (2026-11-16). Before, the regular price lived only on the variant, written at index time.
      onSale: compareAt != null,
      price_old: compareAt,
      discount_percent: compareAt != null && price > 0 ? Math.round((1 - price / compareAt) * 100) : null,
      sku: (row.gtin || "").trim() || null,
      image: images.length ? images[0].src : null,
      images,
      variants: [
        {
          id: `${id}-default`,
          title: "Default",
          price: price ?? 0,
          compare_at_price: compareAt,
          sku: (row.gtin || "").trim() || "",
          inventory_quantity: inStock ? (Number.isFinite(invQty) && invQty > 0 ? invQty : 1) : 0,
        },
      ],
      options: [],
      collections,
      // Store-namespaced Category + CHILD_OF path (keeps the beauty taxonomy isolated
      // from the shared/global fashion categories) — same as Bringo groceries.
      categoryHierarchy: true,
      metafields: [
        { key: "xpert_product_id", value: rawId, namespace: "xpertbeauty" },
        { key: "source_url", value: row.link || "", namespace: "xpertbeauty" },
        { key: "in_stock", value: String(inStock), namespace: "xpertbeauty" },
        { key: "gtin", value: (row.gtin || "").trim(), namespace: "xpertbeauty" },
        { key: "color", value: (row.color || "").trim(), namespace: "xpertbeauty" },
        { key: "google_product_category", value: (row.google_product_category || "").trim(), namespace: "xpertbeauty" },
        { key: "top_group", value: topGroupName, namespace: "xpertbeauty" },
        { key: "list_price", value: listPrice != null ? String(listPrice) : "", namespace: "xpertbeauty" },
        { key: "on_sale", value: String(compareAt != null), namespace: "xpertbeauty" },
        { key: "promo_label", value: (row.custom_label_0 || "").trim(), namespace: "xpertbeauty" },
      ],
      // Private hint for computeInStock() — survives processProducts (same object).
      _inStock: inStock,
      detectedDemographics: demographics,
    };
  }

  // Beauty products: primary category = the most specific LEAF of the feed breadcrumb.
  determineCategory(product) {
    if (product.collections && product.collections.length) {
      return product.collections[product.collections.length - 1].title;
    }
    return product.product_type || "";
  }

  // Real inventory signal from the feed's `availability` column (kept fresh every sync
  // via stampSeen). OOS products stay indexed; downstream filters use coalesce(p.inStock).
  computeInStock(product) {
    return product._inStock !== false;
  }

  // Beauty has no size variants — keep availableSizes empty (avoids a bogus "Default" size).
  computeAvailableSizes() {
    return [];
  }

  // No garment colour — skip the per-product Gemini VISION call the base runs by default
  // (would be ~11k pointless calls). The feed's `color` column is kept as a metafield.
  async detectColorFromImage() {
    return null;
  }

  // ─── Provider interface ─────────────────────────────────────────────────────

  // Download the feed URL to FEED_CACHE_PATH atomically (tmp -> rename), keeping the previous
  // copy as .prev. SANITY GATE: a truncated/empty download must never reach the sync — products
  // absent from a short feed would miss their lastSeenAt stamp and the stale-prune could delete
  // them. We refuse a feed < 1 MB, without the expected header, or with < 80% of the previous
  // row count, and fall back to the last good copy.
  async downloadFeed(url) {
    console.log(`  [XpertBeauty] Downloading feed: ${url}`);
    const res = await fetch(url, { headers: { "User-Agent": "RunaSync/1.0" }, timeout: 120000 });
    if (!res.ok) throw new Error(`feed download failed: HTTP ${res.status}`);
    const text = await res.text();
    const countRows = (t) => Math.max(0, t.split("\n").length - 1);
    if (text.length < 1_000_000 || !/^id,gtin,description,title,link/.test(text)) {
      throw new Error(`feed looks invalid (${text.length} bytes / bad header) — keeping previous copy`);
    }
    if (fs.existsSync(FEED_CACHE_PATH)) {
      const prevRows = countRows(fs.readFileSync(FEED_CACHE_PATH, "utf-8"));
      const newRows = countRows(text);
      if (prevRows > 1000 && newRows < prevRows * 0.8) {
        throw new Error(`feed shrank ${prevRows} -> ${newRows} rows (>20%) — refusing, keeping previous copy`);
      }
      fs.copyFileSync(FEED_CACHE_PATH, FEED_CACHE_PATH + ".prev");
    }
    fs.mkdirSync(path.dirname(FEED_CACHE_PATH), { recursive: true });
    fs.writeFileSync(FEED_CACHE_PATH + ".tmp", text);
    fs.renameSync(FEED_CACHE_PATH + ".tmp", FEED_CACHE_PATH);
    console.log(`  [XpertBeauty] Feed saved: ${FEED_CACHE_PATH} (${text.length} bytes)`);
    return FEED_CACHE_PATH;
  }

  async loadFeed() {
    if (this.rows !== null) return;
    if (!this.csvPath) throw new Error("XpertBeautyProvider requires config.csvPath (feed URL or path to the feed CSV)");
    let file = this.csvPath;
    if (/^https?:\/\//i.test(this.csvPath)) {
      try {
        file = await this.downloadFeed(this.csvPath);
      } catch (e) {
        if (fs.existsSync(FEED_CACHE_PATH)) {
          console.warn(`  [XpertBeauty] ⚠ ${e.message}; using cached ${FEED_CACHE_PATH}`);
          file = FEED_CACHE_PATH;
        } else {
          throw e;
        }
      }
    }
    if (!fs.existsSync(file)) throw new Error(`XpertBeauty feed not found: ${file}`);
    console.log(`  [XpertBeauty] Reading feed: ${file}`);
    const text = fs.readFileSync(file, "utf-8");
    const parsed = parseCsv(text);
    // Keep only published, identifiable rows (guards against feed junk / blank rows).
    this.rows = parsed.filter(
      (r) => (r.id || "").trim() && (r.title || "").trim() && (r.visibility || "published").trim().toLowerCase() !== "hidden"
    );
    console.log(`  [XpertBeauty] Parsed ${parsed.length} rows, ${this.rows.length} usable products`);
  }

  async fetchProducts(options = {}) {
    if (this.rows === null) await this.loadFeed();

    const limit = options.limit || 20;
    const batch = this.rows.slice(this.cursorIndex, this.cursorIndex + limit);
    if (batch.length === 0) return { products: [], nextCursor: null, hasNextPage: false };

    const total = this.rows.length;
    console.log(`  [XpertBeauty] Normalizing ${batch.length} products (${this.cursorIndex + 1}-${this.cursorIndex + batch.length} of ${total})`);

    const products = batch.map((row) => this.normalizeRow(row));
    this.cursorIndex += batch.length;

    const hasNextPage = this.cursorIndex < total;
    return {
      products,
      nextCursor: hasNextPage ? String(this.cursorIndex) : null,
      hasNextPage,
    };
  }

  async fetchCollections() {
    // Return [] so the base SKIPS its global flat createOrUpdateCategories. Beauty
    // categories are created per-product through the store-namespaced Category +
    // CHILD_OF path (categoryHierarchy: true), isolated from the shared fashion tree.
    return [];
  }

  async getShopData() {
    return { currency: "RON", name: this.shopName, domain: SHOP_NAME };
  }

  getCursorState() {
    return { cursorIndex: this.cursorIndex, stats: { ...this.stats } };
  }

  restoreCursorState(state) {
    if (!state) return;
    this.cursorIndex = state.cursorIndex || 0;
    if (state.stats) this.stats = { ...this.stats, ...state.stats };
    console.log(`  [XpertBeauty] Restored cursor: index ${this.cursorIndex}`);
  }
}
